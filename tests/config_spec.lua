local h = require("tests.harness")
local config = require("sqlua.config")

h.test("config defaults", function()
	config.reset()
	local current = config.get()
	h.eq(current.win.width, 40)
	h.eq(current.win.position, "left")
	h.eq(current.execute_on_save, true)
	h.eq(current.auto_execute_helpers, true)
	h.eq(current.completion.enabled, true)
	h.eq(current.completion.filetypes, { "sql", "mysql", "plsql" })
end)

h.test("config deep merges", function()
	config.reset()
	local current = config.setup({
		win = { width = 55 },
		completion = { limit = 50 },
	})
	h.eq(current.win.width, 55)
	h.eq(current.win.position, "left")
	h.eq(current.completion.limit, 50)
	h.eq(current.completion.enabled, true)
	config.reset()
end)

h.test("config accepts disabled mappings", function()
	config.reset()
	local current = config.setup({ mappings = false })
	h.eq(current.mappings, false)
	config.reset()
end)

h.test("config rejects invalid values", function()
	config.reset()
	local ok = pcall(config.setup, { win = { width = 0 } })
	h.eq(ok, false)
	ok = pcall(config.setup, { win = { position = "top" } })
	h.eq(ok, false)
	ok = pcall(config.setup, { completion = { limit = -1 } })
	h.eq(ok, false)
	config.reset()
end)

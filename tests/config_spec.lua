local h = require("tests.harness")
local config = require("lua-dadbod.config")

h.test("config defaults", function()
    config.reset()
    local current = config.get()
    h.eq(current.win.width, 40)
    h.eq(current.win.position, "left")
    h.eq(current.execute_on_save, false)
    h.eq(current.auto_execute_helpers, true)
    h.eq(current.result.max_lines, 10000)
    h.eq(current.result.height, 0.4)
end)

h.test("config deep merges", function()
    config.reset()
    local current = config.setup({
        win = { width = 55 },
        result = { max_lines = 500 },
    })
    h.eq(current.win.width, 55)
    h.eq(current.win.position, "left")
    h.eq(current.result.max_lines, 500)
    config.reset()
end)

h.test("config accepts disabled mappings", function()
    config.reset()
    local current = config.setup({ mappings = false })
    h.eq(current.mappings, false)
    config.reset()
end)

h.test("config gates mappings by section", function()
    config.reset()
    config.setup({ mappings = { global = false, drawer = false } })
    h.eq(config.mappings_enabled("global"), false)
    h.eq(config.mappings_enabled("drawer"), false)
    h.eq(config.mappings_enabled("query"), true)
    config.setup({ mappings = false })
    h.eq(config.mappings_enabled("result"), false)
    config.reset()
end)

h.test("config rejects invalid values", function()
    config.reset()
    local ok = pcall(config.setup, { win = { width = 0 } })
    h.eq(ok, false)
    ok = pcall(config.setup, { win = { position = "top" } })
    h.eq(ok, false)
    ok = pcall(config.setup, { result = { max_lines = -1 } })
    h.eq(ok, false)
    ok = pcall(config.setup, { result = { height = 1.5 } })
    h.eq(ok, false)
    config.reset()
end)
